/// <summary>
/// Specifies the direction of a stack.
/// </summary>
public enum Axis
{
    /// <summary>
    /// Children are placed from left to right.
    /// </summary>
    Horizontal,

    /// <summary>
    /// Children are placed from top to bottom.
    /// </summary>
    Vertical,
}
