using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Mvu.Generators;

/// <summary>
/// Pour chaque <c>[State] partial T Name { get; set; }</c>, écrit :
/// <list type="number">
/// <item>l'implémentation de la propriété : la lecture abonne la vue en cours de calcul,
/// l'écriture (si la valeur change) la fait recalculer — l'équivalent du compilateur de Svelte ;</item>
/// <item>une liaison à double sens, regroupée par type sous <c>Bind</c> : <c>TextField(Bind.Draft)</c>,
/// <c>Checkbox(todo.Bind.Done)</c> — l'équivalent du <c>$draft</c> de SwiftUI, sans réflexion.</item>
/// </list>
/// </summary>
[Generator]
public sealed class StateGenerator : IIncrementalGenerator
{
    const string StateAttribute = "Mvu.State.StateAttribute";
    const string BindName = "Bind";
    const string BindingsTypeName = "StateBindings";

    static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var states = context.SyntaxProvider.ForAttributeWithMetadataName(
            StateAttribute,
            static (node, _) => node is PropertyDeclarationSyntax p
                                && p.Modifiers.Any(SyntaxKind.PartialKeyword)
                                && p.AccessorList is { } list && list.Accessors.All(a => a.Body is null && a.ExpressionBody is null),
            static (ctx, _) => Describe((PropertyDeclarationSyntax)ctx.TargetNode, (IPropertySymbol)ctx.TargetSymbol));

        context.RegisterSourceOutput(states, static (spc, s) => spc.AddSource(s.PropertyHint, s.PropertySource));
        context.RegisterSourceOutput(states.Collect(), static (spc, all) => EmitBindings(spc, all));
    }

    /// <summary>Tout ce qu'il faut savoir d'une propriété [State] (valeurs simples : comparables pour le cache incrémental).</summary>
    readonly record struct StateModel(
        string PropertyHint, string PropertySource,
        string TypeKey, string Header, string Footer, string OwnerHint, string TypeName,
        string Name, string BindingMember, int Access, bool CanBind, bool NeedsNew);

    static StateModel Describe(PropertyDeclarationSyntax syntax, IPropertySymbol property)
    {
        string name = property.Name;
        string type = property.Type.ToDisplayString(TypeFormat);
        string signal = $"__{name}Signal";

        // En-tête et fin communs : espace de noms et chaîne des types englobants, du plus externe au plus interne.
        var ns = property.ContainingNamespace;
        var types = syntax.Ancestors().OfType<TypeDeclarationSyntax>().Reverse().ToList();
        var header = new StringBuilder();
        header.AppendLine("// <auto-generated/>");
        header.AppendLine("#nullable enable");
        if (!ns.IsGlobalNamespace) header.AppendLine($"namespace {ns.ToDisplayString()};");
        foreach (var t in types) header.AppendLine($"partial {Keyword(t)} {t.Identifier.Text}{t.TypeParameterList} {{");
        string footer = string.Concat(types.Select(_ => "}\n"));
        string owner = (ns.IsGlobalNamespace ? "" : ns.ToDisplayString() + ".") + string.Join(".", types.Select(t => t.Identifier.Text));

        // 1. Corps de la propriété.
        var sb = new StringBuilder(header.ToString());
        sb.AppendLine($"    private readonly global::Mvu.State.Signal {signal} = new();");
        sb.AppendLine($"    {syntax.Modifiers} {type} {name}");
        sb.AppendLine("    {");
        foreach (var accessor in syntax.AccessorList!.Accessors)
        {
            string mods = accessor.Modifiers.Count > 0 ? accessor.Modifiers + " " : "";
            if (accessor.Keyword.IsKind(SyntaxKind.GetKeyword))
                sb.AppendLine($"        {mods}get {{ {signal}.Read(); return field; }}");
            else
                sb.AppendLine($"        {mods}{accessor.Keyword.Text} {{ if (!global::System.Collections.Generic.EqualityComparer<{type}>.Default.Equals(field, value)) {{ field = value; {signal}.Notify(); }} }}");
        }
        sb.AppendLine("    }");
        sb.Append(footer);

        // 2. Liaison : seulement pour un état modifiable d'une classe (une structure serait copiée)
        //    qui ne définit pas déjà elle-même un membre Bind.
        var containing = property.ContainingType;
        bool canBind = property.GetMethod is not null
                       && property.SetMethod is { IsInitOnly: false }
                       && containing.IsReferenceType && !containing.IsStatic
                       && containing.GetMembers(BindName).IsEmpty && containing.GetMembers(BindingsTypeName).IsEmpty;
        // Dans une structure, un lambda ne peut pas capturer ses champs : on passe par une variable locale.
        string member = $"global::Mvu.State.Binding<{type}> {name} {{ get {{ var o = _owner; return new(() => o.{name}, v => o.{name} = v); }} }}";
        var innermost = types[types.Count - 1];

        return new StateModel(
            PropertyHint: $"{owner}.{name}.State.g.cs",
            PropertySource: sb.ToString(),
            TypeKey: containing.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            Header: header.ToString(),
            Footer: footer,
            OwnerHint: owner,
            TypeName: innermost.Identifier.Text + innermost.TypeParameterList,
            Name: name,
            BindingMember: member,
            Access: AccessLevel(property),
            CanBind: canBind,
            NeedsNew: BaseHasBindings(containing));
    }

    /// <summary>
    /// Un type <c>StateBindings</c> par classe, exposé par <c>Bind</c>. Privé si tous les états le sont ;
    /// sinon public, avec des liaisons publiques pour les états publics et internes pour les autres
    /// (une structure imbriquée ne peut pas offrir un membre visible de la seule classe englobante).
    /// </summary>
    static void EmitBindings(SourceProductionContext spc, ImmutableArray<StateModel> all)
    {
        foreach (var group in all.Where(s => s.CanBind).GroupBy(s => s.TypeKey))
        {
            var states = group.OrderBy(s => s.Name, StringComparer.Ordinal).ToList();
            var first = states[0];
            bool exposed = states.Any(s => s.Access > 0);
            string visibility = exposed ? "public" : "private";
            string hide = first.NeedsNew ? "new " : "";

            var sb = new StringBuilder(first.Header);
            sb.AppendLine("    /// <summary>Liaisons à double sens vers les états <c>[State]</c> : <c>TextField(Bind.Draft)</c>.</summary>");
            sb.AppendLine($"    {visibility} {hide}{BindingsTypeName} {BindName} => new(this);");
            sb.AppendLine();
            sb.AppendLine($"    {visibility} {hide}readonly struct {BindingsTypeName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        readonly {first.TypeName} _owner;");
            sb.AppendLine($"        public {BindingsTypeName}({first.TypeName} owner) => _owner = owner;");
            foreach (var s in states)
                sb.AppendLine($"        {(!exposed || s.Access == 2 ? "public" : "internal")} {s.BindingMember}");
            sb.AppendLine("    }");
            sb.Append(first.Footer);

            spc.AddSource($"{first.OwnerHint}.Bind.g.cs", sb.ToString());
        }
    }

    /// <summary>Visibilité de la liaison : la plus restrictive de la lecture et de l'écriture (0 privé, 1 interne, 2 public).</summary>
    static int AccessLevel(IPropertySymbol property)
    {
        var get = property.GetMethod?.DeclaredAccessibility ?? Accessibility.Private;
        var set = property.SetMethod?.DeclaredAccessibility ?? Accessibility.Private;
        var min = (Accessibility)Math.Min((int)get, (int)set);
        return min switch
        {
            Accessibility.Public => 2,
            Accessibility.Private or Accessibility.NotApplicable => 0,
            _ => 1,
        };
    }

    /// <summary>Un type de base a déjà (ou recevra) son propre <c>Bind</c> : le nôtre doit le masquer explicitement.</summary>
    static bool BaseHasBindings(INamedTypeSymbol type)
    {
        for (var t = type.BaseType; t is not null; t = t.BaseType)
        {
            if (!t.GetMembers(BindName).IsEmpty) return true;
            if (t.GetMembers().OfType<IPropertySymbol>().Any(p =>
                    p.SetMethod is { IsInitOnly: false }
                    && p.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == StateAttribute)))
                return true;
        }
        return false;
    }

    static string Keyword(TypeDeclarationSyntax t) => t switch
    {
        RecordDeclarationSyntax r when r.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) => "record struct",
        RecordDeclarationSyntax => "record",
        _ => t.Keyword.Text,
    };
}
