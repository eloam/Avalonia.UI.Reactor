using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MartletUI.Generators;

/// <summary>
/// Generates the code of the <c>[State]</c> properties.
/// </summary>
/// <remarks>
/// For each <c>[State] partial T Name { get; set; }</c>, the generator writes:
/// <list type="number">
/// <item><description>the implementation of the property: reading it subscribes the view being evaluated, and writing it
/// (when the value changes) re-evaluates that view, the equivalent of the Svelte compiler;</description></item>
/// <item><description>a two-way binding, grouped by type under <c>Bind</c>: <c>TextField(Bind.Draft)</c>,
/// <c>Checkbox(todo.Bind.Done)</c>, the equivalent of <c>$draft</c> in SwiftUI, without reflection.</description></item>
/// </list>
/// </remarks>
[Generator]
public sealed class StateGenerator : IIncrementalGenerator
{
    private const string StateAttribute = "MartletUI.State.StateAttribute";
    private const string BindName = "Bind";
    private const string BindingsTypeName = "StateBindings";

    private static readonly SymbolDisplayFormat s_typeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<StateModel> states = States(context);
        context.RegisterSourceOutput(states, static (spc, s) => spc.AddSource(s.PropertyHint, s.PropertySource));
        context.RegisterSourceOutput(states.Collect(), static (spc, all) =>
        {
            foreach ((string hintName, string text) in BindingSources(all))
                spc.AddSource(hintName, text);
        });
    }

    /// <summary>
    /// Creates the pipeline that describes the <c>[State]</c> properties of a compilation.
    /// </summary>
    /// <remarks>
    /// The view builder generator shares it: generators do not see each other's code, so it resolves the calls of
    /// the blocks (<c>TextField(Bind.Email)</c>) in a compilation that contains this code (see <see cref="Sources"/>).
    /// </remarks>
    /// <param name="context">The context of the generator.</param>
    /// <returns>The description of each <c>[State]</c> property.</returns>
    internal static IncrementalValuesProvider<StateModel> States(IncrementalGeneratorInitializationContext context) =>
        context.SyntaxProvider.ForAttributeWithMetadataName(
            StateAttribute,
            static (node, _) => node is PropertyDeclarationSyntax p
                && p.Modifiers.Any(SyntaxKind.PartialKeyword)
                && p.AccessorList is { } list
                && list.Accessors.All(a => a.Body is null && a.ExpressionBody is null),
            static (ctx, _) => Describe((PropertyDeclarationSyntax)ctx.TargetNode, (IPropertySymbol)ctx.TargetSymbol));

    /// <summary>
    /// Gets the code that this generator writes for the <c>[State]</c> properties of a compilation.
    /// </summary>
    /// <param name="all">The description of every <c>[State]</c> property of the compilation.</param>
    /// <returns>The name and the text of each generated file.</returns>
    internal static IEnumerable<(string HintName, string Text)> Sources(ImmutableArray<StateModel> all) =>
        all.Select(s => (s.PropertyHint, s.PropertySource)).Concat(BindingSources(all));

    private static StateModel Describe(PropertyDeclarationSyntax syntax, IPropertySymbol property)
    {
        string name = property.Name;
        string type = property.Type.ToDisplayString(s_typeFormat);
        string signal = $"__{name}Signal";

        // Shared header and footer: the namespace and the chain of containing types, from the outermost to the innermost.
        INamespaceSymbol ns = property.ContainingNamespace;
        var types = syntax.Ancestors().OfType<TypeDeclarationSyntax>().Reverse().ToList();
        var header = new StringBuilder();
        header.AppendLine("// <auto-generated/>");
        header.AppendLine("#nullable enable");
        if (!ns.IsGlobalNamespace)
        {
            header.AppendLine($"namespace {ns.ToDisplayString()};");
        }

        foreach (TypeDeclarationSyntax containingType in types)
        {
            header.AppendLine($"partial {Keyword(containingType)} {containingType.Identifier.Text}{containingType.TypeParameterList} {{");
        }

        string footer = string.Concat(types.Select(_ => "}\n"));
        string owner = (ns.IsGlobalNamespace ? string.Empty : ns.ToDisplayString() + ".")
            + string.Join(".", types.Select(t => t.Identifier.Text));

        // 1. The body of the property. Hot reload adds the property to the objects that already exist without running their
        //    initializers: their signal is created by its first use. The initializer of the signal is needed too: it makes
        //    hot reload update the constructors, and with them the initial value of the property in the new objects.
        var sb = new StringBuilder(header.ToString());
        sb.AppendLine($"    private global::MartletUI.State.Signal? {signal}Storage = new(nameof({name}));");
        sb.AppendLine(
            $"    private global::MartletUI.State.Signal {signal} => global::System.Threading.LazyInitializer.EnsureInitialized(ref {signal}Storage, static () => new global::MartletUI.State.Signal(nameof({name})));");
        sb.AppendLine($"    {syntax.Modifiers} {type} {name}");
        sb.AppendLine("    {");
        foreach (AccessorDeclarationSyntax accessor in syntax.AccessorList!.Accessors)
        {
            string modifiers = accessor.Modifiers.Count > 0 ? accessor.Modifiers + " " : string.Empty;
            if (accessor.Keyword.IsKind(SyntaxKind.GetKeyword))
            {
                sb.AppendLine($"        {modifiers}get {{ {signal}.Read(); return field; }}");
            }
            else
            {
                sb.AppendLine(
                    $"        {modifiers}{accessor.Keyword.Text} {{ if (!global::System.Collections.Generic.EqualityComparer<{type}>.Default.Equals(field, value)) {{ {signal}.EnsureWritable(); field = value; {signal}.Notify(); }} }}");
            }
        }

        sb.AppendLine("    }");
        sb.Append(footer);

        // 2. The binding: only for a settable state of a class (a struct would be copied) that does not define a Bind
        //    member itself.
        INamedTypeSymbol containing = property.ContainingType;
        bool canBind = property.GetMethod is not null
            && property.SetMethod is { IsInitOnly: false }
            && containing.IsReferenceType
            && !containing.IsStatic
            && containing.GetMembers(BindName).IsEmpty
            && containing.GetMembers(BindingsTypeName).IsEmpty;

        // In a struct, a lambda cannot capture the fields of the struct: the owner goes through a local variable. The
        // owner and the name of the property identify a control bound to it among its siblings.
        string member =
            $"global::MartletUI.State.Binding<{type}> {name} {{ get {{ var o = _owner; return new(() => o.{name}, v => o.{name} = v, o, nameof(o.{name})); }} }}";
        TypeDeclarationSyntax innermost = types[types.Count - 1];

        return new StateModel(
            PropertyHint: $"{owner}.{name}.State.g.cs",
            PropertySource: sb.ToString(),
            TypeKey: containing.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            Header: header.ToString(),
            Footer: footer,
            OwnerHint: owner,
            TypeName: innermost.Identifier.Text + innermost.TypeParameterList,
            Name: name,
            BindingMember: member,
            Access: AccessLevel(property),
            CanBind: canBind,
            NeedsNew: BaseHasBindings(containing));
    }

    // One StateBindings type per class, exposed by Bind. It is private if every state is; otherwise it is public, with
    // public bindings for public states and internal ones for the others (a nested struct cannot offer a member visible
    // to its containing class only).
    private static IEnumerable<(string HintName, string Text)> BindingSources(ImmutableArray<StateModel> all)
    {
        foreach (IGrouping<string, StateModel> group in all.Where(s => s.CanBind).GroupBy(s => s.TypeKey))
        {
            var states = group.OrderBy(s => s.Name, StringComparer.Ordinal).ToList();
            StateModel first = states[0];
            bool exposed = states.Any(s => s.Access > 0);
            string visibility = exposed ? "public" : "private";
            string hide = first.NeedsNew ? "new " : string.Empty;

            var sb = new StringBuilder(first.Header);
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Gets the two-way bindings to the <c>[State]</c> properties: <c>TextField(Bind.Draft)</c>.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    {visibility} {hide}{BindingsTypeName} {BindName} => new(this);");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// Provides the two-way bindings to the <c>[State]</c> properties of an instance.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    {visibility} {hide}readonly struct {BindingsTypeName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        private readonly {first.TypeName} _owner;");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>");
            sb.AppendLine($"        /// Initializes a new instance of the <see cref=\"{BindingsTypeName}\"/> structure.");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        /// <param name=\"owner\">The instance whose state the bindings read and write.</param>");
            sb.AppendLine($"        public {BindingsTypeName}({first.TypeName} owner)");
            sb.AppendLine("        {");
            sb.AppendLine("            _owner = owner;");
            sb.AppendLine("        }");
            foreach (StateModel state in states)
            {
                sb.AppendLine();
                sb.AppendLine("        /// <summary>");
                sb.AppendLine($"        /// Gets a two-way binding to the <c>{state.Name}</c> property.");
                sb.AppendLine("        /// </summary>");
                sb.AppendLine($"        {(!exposed || state.Access == 2 ? "public" : "internal")} {state.BindingMember}");
            }

            sb.AppendLine("    }");
            sb.Append(first.Footer);

            yield return ($"{first.OwnerHint}.Bind.g.cs", sb.ToString());
        }
    }

    // The access level of a binding: the most restrictive of the getter and the setter (0 private, 1 internal, 2 public).
    private static int AccessLevel(IPropertySymbol property)
    {
        Accessibility get = property.GetMethod?.DeclaredAccessibility ?? Accessibility.Private;
        Accessibility set = property.SetMethod?.DeclaredAccessibility ?? Accessibility.Private;
        var min = (Accessibility)Math.Min((int)get, (int)set);
        return min switch
        {
            Accessibility.Public => 2,
            Accessibility.Private or Accessibility.NotApplicable => 0,
            _ => 1,
        };
    }

    // A base type already has (or will receive) its own Bind: ours must hide it explicitly.
    private static bool BaseHasBindings(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? baseType = type.BaseType; baseType is not null; baseType = baseType.BaseType)
        {
            if (!baseType.GetMembers(BindName).IsEmpty)
            {
                return true;
            }

            if (baseType.GetMembers().OfType<IPropertySymbol>().Any(p =>
                    p.SetMethod is { IsInitOnly: false }
                    && p.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == StateAttribute)))
            {
                return true;
            }
        }

        return false;
    }

    private static string Keyword(TypeDeclarationSyntax type) => type switch
    {
        RecordDeclarationSyntax record when record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) => "record struct",
        RecordDeclarationSyntax => "record",
        _ => type.Keyword.Text,
    };

    // Everything the generator needs to know about a [State] property, as plain values that the incremental cache can
    // compare.
    internal readonly record struct StateModel(
        string PropertyHint,
        string PropertySource,
        string TypeKey,
        string Header,
        string Footer,
        string OwnerHint,
        string TypeName,
        string Name,
        string BindingMember,
        int Access,
        bool CanBind,
        bool NeedsNew);
}
