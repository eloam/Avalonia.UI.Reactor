namespace MartletUI.Primitives;

/// <summary>
/// Specifies the horizontal alignment of text.
/// </summary>
public enum TextAlign
{
    /// <summary>
    /// Text is aligned to the start of the line.
    /// </summary>
    Start,

    /// <summary>
    /// Text is centered.
    /// </summary>
    Center,

    /// <summary>
    /// Text is aligned to the end of the line.
    /// </summary>
    End,
}
