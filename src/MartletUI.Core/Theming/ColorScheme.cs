namespace MartletUI.Theming;

/// <summary>
/// Specifies whether a theme is light or dark.
/// </summary>
public enum ColorScheme
{
    /// <summary>
    /// Dark text on a light background.
    /// </summary>
    Light,

    /// <summary>
    /// Light text on a dark background.
    /// </summary>
    Dark,
}
